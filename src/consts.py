# consts.py
# Единая точка правки всех параметров конвейера UART -> MQTT

# --- Размеры буферов ---
MAX_UART_PAYLOAD_LEN = 1536                  # Максимальный размер пакета (Base64 payload)
UART_RX_BUF_SIZE     = 1024                  # Размер системного кольцевого буфера C-драйвера (может быть меньше 3 КБ)

# --- Таймауты UART ---
UART_TIMEOUT_MS      = 20                    # Пауза тишины для определения конца кадра (мс)
UART_TIMEOUT_CHAR_MS = 2                     # Таймаут между символами внутри C-драйвера (мс)

# --- Управляющие байты (Flow Control) ---
ACK_BYTE             = b'\x06'               # Байт подтверждения успешной отправки (ASCII ACK)
NACK_BYTE            = b'\x15'               # Байт ошибки / повторного запроса (ASCII NACK)

# --- Настройки MQTT ---
REG_PAYLOAD_TOPIC_ID = 3                     # ID регистра для отправки данных
